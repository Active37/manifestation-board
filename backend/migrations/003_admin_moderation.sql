CREATE TABLE admin_sessions (
  token_hash text PRIMARY KEY,
  csrf_hash text NOT NULL,
  moderator_id uuid NOT NULL REFERENCES moderators(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT admin_sessions_token_hash_check CHECK (token_hash ~ '^[a-f0-9]{64}$'),
  CONSTRAINT admin_sessions_csrf_hash_check CHECK (csrf_hash ~ '^[a-f0-9]{64}$')
);

CREATE INDEX admin_sessions_expires_at_idx
  ON admin_sessions (expires_at);

CREATE TABLE moderation_actions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id uuid NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  moderator_id uuid REFERENCES moderators(id) ON DELETE SET NULL,
  action text NOT NULL,
  from_status text NOT NULL,
  to_status text NOT NULL,
  from_rejected_at timestamptz,
  to_rejected_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  undone_at timestamptz,
  undone_by uuid REFERENCES moderators(id) ON DELETE SET NULL,
  CONSTRAINT moderation_actions_action_check
    CHECK (action IN ('approve', 'reject', 'restore')),
  CONSTRAINT moderation_actions_from_status_check
    CHECK (from_status IN ('live', 'held', 'hidden', 'rejected')),
  CONSTRAINT moderation_actions_to_status_check
    CHECK (to_status IN ('live', 'held', 'hidden', 'rejected')),
  CONSTRAINT moderation_actions_undo_pair_check
    CHECK ((undone_at IS NULL) = (undone_by IS NULL))
);

CREATE INDEX moderation_actions_undo_idx
  ON moderation_actions (post_id, id DESC)
  WHERE undone_at IS NULL;

CREATE INDEX moderation_actions_created_at_idx
  ON moderation_actions (created_at);