CREATE TABLE moderation_actions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id uuid NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  moderator_id uuid REFERENCES moderators(id) ON DELETE SET NULL,
  action text NOT NULL CHECK (action IN ('approve', 'reject', 'restore')),
  from_status text NOT NULL CHECK (from_status IN ('held', 'live', 'rejected')),
  to_status text NOT NULL CHECK (to_status IN ('held', 'live', 'rejected')),
  from_rejected_at timestamptz,
  to_rejected_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  undone_at timestamptz,
  undone_by uuid REFERENCES moderators(id) ON DELETE SET NULL
);

CREATE INDEX moderation_actions_undo_idx
  ON moderation_actions (post_id, id DESC)
  WHERE undone_at IS NULL;

CREATE INDEX posts_rejected_at_idx
  ON posts (rejected_at)
  WHERE status = 'rejected';
